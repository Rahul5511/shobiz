import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import { parseTemplate } from '@angular/compiler';
import { format, resolveConfig } from 'prettier';
import { identity, layerMatrix, multiply } from './svg-geometry.mjs';

// Offline, deterministic conversion. The export remains a reference, never a runtime dependency.
const root = process.cwd();
const source = path.join(root, 'angular-design-library');
const target = path.join(root, 'src/app/shared/design-system');
const tokens = JSON.parse(fs.readFileSync(path.join(source, 'tokens/all-tokens.json'), 'utf8'));
const slug = (value) =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const prefix = (collection) =>
  ({
    'Primitive: Color': 'palette-',
    'Primitive: Typography': 'type-scale-',
    'Semantic: Typography': 'type-',
    'Primitive: Type': 'font-',
    'Semantic: Type App': 'app-type-',
    'Semantic: Type Web': 'web-type-',
    'Text Style Variables': 'text-style-',
  })[collection] ?? '';
const normalize = (token) => {
  let value = token.cssValue;
  if (/weight/i.test(token.name) && value.startsWith('"')) {
    return (
      { regular: '400', medium: '500', semibold: '600', bold: '700' }[
        JSON.parse(value).toLowerCase().replaceAll(' ', '')
      ] ?? value
    );
  }
  if (token.resolved?.floatValue !== undefined && !/weight|opacity/i.test(token.name))
    value += 'px';
  return value;
};
const groups = new Map();
const conflicts = [];
// Components precede foundations: they describe the controls being integrated.
for (const token of [...tokens].sort(
  (a, b) => (a.source === 'components' ? 0 : 1) - (b.source === 'components' ? 0 : 1),
)) {
  const name = `--ngage-${prefix(token.collection)}${slug(token.name)}`;
  const modes = groups.get(name) ?? new Map();
  const value = normalize(token);
  if (modes.has(token.mode) && modes.get(token.mode) !== value) {
    conflicts.push({
      name,
      mode: token.mode,
      selected: modes.get(token.mode),
      alternative: value,
      sourceVariable: token.cssVariable,
    });
  } else modes.set(token.mode, value);
  groups.set(name, modes);
}
const declarations = (entries) => entries.map(([name, value]) => `  ${name}: ${value};`).join('\n');
const defaults = [...groups].map(([name, modes]) => [
  name,
  modes.get('Light') ?? modes.get('Desktop') ?? modes.values().next().value,
]);
const dark = [...groups]
  .filter(([, modes]) => modes.has('Dark'))
  .map(([name, modes]) => [name, modes.get('Dark')]);
let css = `/* Generated by tools/design-system/generate.mjs from the local Figma export. */\n:root,\n.ngage-theme {\n${declarations(defaults)}\n}\n\n.night-theme,\n[data-ngage-theme='dark'] {\n  color-scheme: dark;\n${declarations(dark)}\n}\n`;
for (const [mode, width] of [
  ['Tablet', 1024],
  ['Mobile', 640],
]) {
  const values = [...groups]
    .filter(([, modes]) => modes.has(mode))
    .map(([name, modes]) => [name, modes.get(mode)]);
  css += `\n@media (max-width: ${width}px) {\n  :root, .ngage-theme {\n${declarations(values).replaceAll('\n', '\n  ')}\n  }\n}\n`;
}
fs.writeFileSync(path.join(target, 'styles/exported-tokens.css'), css);
fs.writeFileSync(
  path.join(target, 'token-conflicts.json'),
  JSON.stringify(
    {
      policy:
        'First exported component definition wins; foundations fill missing names. Conflicting alternatives are retained here for review.',
      conflicts,
    },
    null,
    2,
  ) + '\n',
);

// Consolidate responsive typography into utilities; no component per text specimen.
const textGroups = [...groups.keys()].filter((name) =>
  /^--ngage-type-(heading|text)-.*-size$/.test(name),
);
let typography =
  '/* Generated responsive typography utilities. Values inherit the current theme. */\n';
for (const name of textGroups) {
  const stem = name.slice(0, -5);
  const utility = stem.replace('--ngage-type-', 'ngage-');
  const inferredWeight = /semibold/.test(stem)
    ? 600
    : /medium/.test(stem)
      ? 500
      : /bold/.test(stem)
        ? 700
        : 400;
  typography += `.${utility} { font-family: var(--ngage-font-family); font-size: var(${name}); line-height: var(${stem}-line-height); letter-spacing: var(${stem}-letter-spacing, 0px); font-weight: var(${stem}-weight, ${inferredWeight}); }\n`;
}
typography += `.ngage-text-s { font: var(--ngage-font-regular) var(--ngage-text-s-size)/var(--ngage-text-s-line-height) var(--ngage-font-family); }\n.ngage-text-m { font: var(--ngage-font-regular) var(--ngage-text-m-size)/var(--ngage-text-m-line-height) var(--ngage-font-family); }\n.ngage-text-l { font: var(--ngage-font-regular) var(--ngage-text-l-size)/var(--ngage-text-l-line-height) var(--ngage-font-family); }\n.ngage-medium { font-weight: var(--ngage-font-medium); }\n`;
fs.writeFileSync(path.join(target, 'styles/typography.css'), typography);
console.log(
  `Generated ${groups.size} named tokens and ${textGroups.length} typography utilities; recorded ${conflicts.length} conflicting mode entries.`,
);

// Reassemble icon layers into one SVG per geometry, retaining source offsets.
// Color is supplied at runtime using a CSS mask, so tone/state needs no asset copy.
const iconNames = new Set();
const registry = {};
const assets = path.join(root, 'public/ngage/library/icons');
fs.mkdirSync(assets, { recursive: true });
for (const family of fs.readdirSync(path.join(source, 'components'))) {
  const dir = path.join(source, 'components', family);
  if (!fs.statSync(dir).isDirectory()) continue;
  for (const variant of fs.readdirSync(dir)) {
    const folder = path.join(dir, variant);
    const meta = JSON.parse(fs.readFileSync(path.join(folder, 'metadata.json'), 'utf8'));
    const style = meta.name.match(/Style=([^,]+)/)?.[1];
    const shape = meta.name.match(/Type=([^,]+)/)?.[1];
    if (!style || !shape || !/^(Stroke|Solid|Duotone|Twotone|Bulk)$/i.test(style)) continue;
    const rules = new Map();
    postcss.parse(fs.readFileSync(path.join(folder, 'component.css'), 'utf8')).walkRules((rule) => {
      const cls = rule.selector.match(/\.ngage-node-\d+/)?.[0].slice(1);
      if (cls)
        rules.set(
          cls,
          Object.fromEntries(
            rule.nodes
              .filter((node) => node.type === 'decl')
              .map((node) => [node.prop, node.value]),
          ),
        );
    });
    const layers = [];
    const visit = (node, parentMatrix = identity) => {
      if (!node.attributes) return;
      const cls = node.attributes
        .find((a) => a.name === 'class')
        ?.value.split(' ')
        .find((v) => v.startsWith('ngage-node-'));
      const rule = rules.get(cls) ?? {};
      const matrix = multiply(parentMatrix, layerMatrix(rule));
      const hash = rule['background-image']?.match(/--ngage-vector-([a-z0-9]+)/)?.[1];
      if (hash) {
        let svg = fs.readFileSync(path.join(source, 'assets/vectors', hash + '.svg'), 'utf8');
        const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
        const inside = svg.replace(/^<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
        layers.push(
          `<g transform="matrix(${matrix.join(' ')})"><svg width="${parseFloat(rule.width)}" height="${parseFloat(rule.height)}" viewBox="${viewBox}">${inside}</svg></g>`,
        );
      }
      for (const child of node.children ?? []) visit(child, matrix);
    };
    parseTemplate(
      fs.readFileSync(path.join(folder, 'component.html'), 'utf8'),
      'icon.html',
    ).nodes.forEach((node) => visit(node));
    if (!layers.length) continue;
    const name = `${family}-${slug(style)}-${slug(shape)}`;
    fs.writeFileSync(
      path.join(assets, name + '.svg'),
      `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${meta.size.x} ${meta.size.y}">${layers.join('')}</svg>\n`,
    );
    registry[`${family}/${slug(style)}/${slug(shape)}`] = `ngage/library/icons/${name}.svg`;
    iconNames.add(family);
  }
}
fs.writeFileSync(
  path.join(target, 'components/icon-assets.ts'),
  `// Generated from angular-design-library; geometry only, no runtime export dependency.\nexport type NgageGlyphName = ${[...iconNames].map((v) => `'${v}'`).join(' | ')};\nexport const NGAGE_ICON_ASSETS: Readonly<Record<string, string>> = ${JSON.stringify(registry, null, 2)};\n`,
);
console.log(
  `Generated ${Object.keys(registry).length} icon geometries in ${iconNames.size} families.`,
);

// Regeneration uses the repository format, keeping checked-in artifacts stable.
for (const relative of [
  'styles/exported-tokens.css',
  'styles/typography.css',
  'components/icon-assets.ts',
  'token-conflicts.json',
]) {
  const file = path.join(target, relative);
  const options = (await resolveConfig(file)) ?? {};
  fs.writeFileSync(
    file,
    await format(fs.readFileSync(file, 'utf8'), { ...options, filepath: file }),
  );
}
